import os
from google.colab import userdata
os.environ["GEMINI_API_KEY"] = userdata.get("GEMINI_API_KEY")
print("API key loaded:", bool(os.environ["GEMINI_API_KEY"]))

import time
from google import genai

client = genai.Client(api_key=os.environ["GEMINI_API_KEY"])
model = "gemini-3.5-flash-lite"

question = input("Ask your question: ")      # type: What is AI?

for attempt in range(1, 5):
    try:
        start = time.time()
        response = client.models.generate_content(model=model, contents=question)
        latency = (time.time() - start) * 1000
        break
    except Exception as e:
        print(f"Attempt {attempt} failed: {e}. Retrying...")
        time.sleep(attempt * 2)

usage = response.usage_metadata
print("\nQuestion:", question)
print("Answer  :", response.text)
print("\nInput tokens :", usage.prompt_token_count)
print("Output tokens:", usage.candidates_token_count)
print("Total tokens :", usage.total_token_count)
print("Latency (ms) :", round(latency))